import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    const systemPrompt = `You are AgroWaste AI Assistant, an expert in composting and agricultural waste management. You help users understand:

1. **Composting Basics**: How to compost agricultural waste, optimal conditions (temperature 40-60°C, moisture 40-60%), and timeline (25-30 days).

2. **Waste Types**: Best practices for composting different materials:
   - Crop residues (straw, stalks)
   - Food waste (vegetable scraps, fruit peels)
   - Green waste (grass clippings, leaves)
   - Coffee grounds, eggshells

3. **Troubleshooting**: Common issues like:
   - High temperature (>65°C): Turn pile, add water
   - Low moisture (<40%): Add water while turning
   - High moisture (>60%): Add dry materials, improve drainage
   - Slow decomposition: Add nitrogen-rich materials

4. **Fertilizer Quality**: When compost is ready (dark, crumbly, earthy smell), how to use it, and nutrient benefits.

Keep answers concise, practical, and easy to understand. Use simple language suitable for farmers and students. Include specific numbers and actionable advice.`;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limits exceeded, please try again later." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI usage limit reached. Please try again later." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI service error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("compost-chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
